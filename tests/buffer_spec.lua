local helpers = require("tests.helpers")
local buffer = require("openbao.buffer")
local config = require("openbao.config")

local function open(full, opts)
  buffer.open(full, opts)
  assert(
    vim.wait(10000, function()
      return buffer.find(full) ~= nil or (opts and opts.version and vim.b.openbao ~= nil)
    end, 10),
    "buffer did not open"
  )
  return vim.api.nvim_get_current_buf()
end

local function saved(buf)
  return vim.wait(10000, function()
    return not vim.bo[buf].modified
  end, 10)
end

describe("secret buffer", function()
  local dir, restore
  before_each(function()
    dir = helpers.setup_fake({ secrets = { ["secret/app/db"] = { USER = "u", PASS = "p w" } } })
    restore = function() end
  end)
  after_each(function()
    restore()
    vim.cmd("silent! %bwipeout!")
  end)

  it("shows the secret as dotenv and hardens the buffer", function()
    local buf = open("secret/app/db")
    assert.are.same({ 'PASS="p w"', "USER=u" }, vim.api.nvim_buf_get_lines(buf, 0, -1, false))
    assert.are.equal("acwrite", vim.bo[buf].buftype)
    assert.are.equal("dotenv", vim.bo[buf].filetype)
    assert.is_false(vim.bo[buf].swapfile)
    assert.is_false(vim.bo[buf].undofile)
    assert.are.equal(-1, vim.bo[buf].undolevels)
    assert.are.equal("openbao://secret/app/db", vim.api.nvim_buf_get_name(buf))
  end)

  it("conceals values until revealed", function()
    local buf = open("secret/app/db")
    local ns = vim.api.nvim_create_namespace("openbao")
    assert.are.equal(2, #vim.api.nvim_buf_get_extmarks(buf, ns, 0, -1, {}))
    buffer.toggle_reveal(buf)
    assert.are.equal(0, #vim.api.nvim_buf_get_extmarks(buf, ns, 0, -1, {}))
    buffer.toggle_reveal(buf)
    assert.are.equal(2, #vim.api.nvim_buf_get_extmarks(buf, ns, 0, -1, {}))
  end)

  it("does not conceal when the option is off", function()
    config.options.conceal = false
    local buf = open("secret/app/db")
    local ns = vim.api.nvim_create_namespace("openbao")
    assert.are.equal(0, #vim.api.nvim_buf_get_extmarks(buf, ns, 0, -1, {}))
  end)

  it(":write sends the edit to OpenBao and keeps other keys", function()
    local buf = open("secret/app/db")
    vim.api.nvim_buf_set_lines(buf, 0, -1, false, { 'PASS="p w"', "USER=changed", "NEW=1" })
    vim.cmd("write")
    assert.is_true(saved(buf))
    assert.are.same({ USER = "changed", PASS = "p w", NEW = "1" }, helpers.latest(dir, "secret/app/db"))
    assert.are.equal(2, buffer.state(buf).version)
  end)

  it("asks before removing keys, and cancels cleanly", function()
    local stub, prompts = helpers.stub_select({ ["REMOVED"] = "Cancel" })
    restore = stub
    local buf = open("secret/app/db")
    vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "USER=u" })
    vim.cmd("write")
    vim.wait(300, function()
      return false
    end)
    assert.matches("PASS", prompts[1])
    assert.is_true(vim.bo[buf].modified)
    assert.are.same({ USER = "u", PASS = "p w" }, helpers.latest(dir, "secret/app/db"))
  end)

  it("removes keys once confirmed", function()
    restore = helpers.stub_select({ ["REMOVED"] = "Write" })
    local buf = open("secret/app/db")
    vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "USER=u" })
    vim.cmd("write")
    assert.is_true(saved(buf))
    assert.are.same({ USER = "u" }, helpers.latest(dir, "secret/app/db"))
  end)

  it("blocks the write on a parse error and refuses an empty secret", function()
    local buf = open("secret/app/db")
    vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "not valid" })
    pcall(vim.cmd, "write") -- the synchronous error notification is raised by :write in headless mode
    assert.is_true(vim.bo[buf].modified)
    vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "# only a comment" })
    pcall(vim.cmd, "write")
    assert.is_true(vim.bo[buf].modified)
    assert.are.same({ USER = "u", PASS = "p w" }, helpers.latest(dir, "secret/app/db"))
  end)

  it("detects a remote change (cas) and `:w!` overwrites", function()
    local buf = open("secret/app/db")
    local kv = require("openbao.kv")
    helpers.await(function(done)
      kv.put("secret/app/db", { USER = "remote" }, { cas = 1 }, done)
    end)
    vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "USER=mine" })
    restore = helpers.stub_select({ ["REMOVED"] = "Write" })
    vim.cmd("write")
    vim.wait(500, function()
      return not vim.bo[buf].modified
    end)
    assert.is_true(vim.bo[buf].modified)
    assert.are.same({ USER = "remote" }, helpers.latest(dir, "secret/app/db"))
    vim.cmd("write!")
    assert.is_true(saved(buf))
    assert.are.same({ USER = "mine" }, helpers.latest(dir, "secret/app/db"))
  end)

  it("creates a new secret with cas=0 and refuses to clobber a concurrent creation", function()
    local buf = open("secret/new/one", { create = true })
    assert.is_true(buffer.state(buf).new)
    vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "A=1" })
    vim.cmd("write")
    assert.is_true(saved(buf))
    assert.are.same({ A = "1" }, helpers.latest(dir, "secret/new/one"))
  end)

  it("opens non-string secrets as JSON", function()
    helpers.await(function(done)
      require("openbao.kv").put("secret/json", { n = 1, nested = { a = "b" } }, { cas = 0 }, done)
    end)
    local buf = open("secret/json")
    assert.are.equal("json", vim.bo[buf].filetype)
    vim.api.nvim_buf_set_lines(buf, 0, -1, false, { '{"n": 2, "nested": {"a": "b"}}' })
    vim.cmd("write")
    assert.is_true(saved(buf))
    assert.are.same({ n = 2, nested = { a = "b" } }, helpers.latest(dir, "secret/json"))
  end)

  it("opens an old version read-only", function()
    helpers.await(function(done)
      require("openbao.kv").put("secret/app/db", { USER = "v2" }, { cas = 1 }, done)
    end)
    local buf = open("secret/app/db", { version = 1 })
    assert.are.same({ 'PASS="p w"', "USER=u" }, vim.api.nvim_buf_get_lines(buf, 0, -1, false))
    assert.is_false(vim.bo[buf].modifiable)
    assert.matches("@v1", vim.api.nvim_buf_get_name(buf))
  end)

  it("reloads remote content", function()
    local buf = open("secret/app/db")
    helpers.await(function(done)
      require("openbao.kv").put("secret/app/db", { USER = "remote" }, { cas = 1 }, done)
    end)
    buffer.reload(buf)
    assert.is_true(vim.wait(10000, function()
      return vim.api.nvim_buf_get_lines(buf, 0, -1, false)[1] == "USER=remote"
    end, 10))
  end)
end)
