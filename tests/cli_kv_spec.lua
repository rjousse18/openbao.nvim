local helpers = require("tests.helpers")
local cli = require("openbao.cli")
local config = require("openbao.config")
local kv = require("openbao.kv")

describe("cli", function()
  it("reports a missing binary through the callback", function()
    config.setup({ binary = "/nonexistent/bao" })
    local res = helpers.await(function(done)
      cli.run({ "status" }, nil, done)
    end)
    assert.is_false(res.ok)
    assert.matches("not executable", res.stderr)
  end)

  it("decodes JSON output and never puts stdin in the arguments", function()
    local dir = helpers.setup_fake()
    local err = helpers.await(function(done)
      kv.put("secret/app", { TOKEN = "s3cret" }, { cas = 0 }, done)
    end)
    assert.is_nil(err)
    for _, call in ipairs(helpers.calls(dir)) do
      assert.is_nil(call:find("s3cret", 1, true))
    end
  end)

  it("sets the address for both binaries", function()
    helpers.setup_fake()
    config.options.address = "http://127.0.0.1:8200"
    config.options.binary = "env"
    local res = helpers.await(function(done)
      cli.run({}, nil, done)
    end)
    assert.matches("BAO_ADDR=http://127.0.0.1:8200", res.stdout)
    assert.matches("VAULT_ADDR=http://127.0.0.1:8200", res.stdout)
  end)
end)

describe("kv", function()
  local dir
  before_each(function()
    dir = helpers.setup_fake({ secrets = { ["secret/app/db"] = { USER = "u" }, ["secret/app/api/key"] = { K = "1" } } })
  end)

  it("gets a secret with its version", function()
    local err, secret = helpers.await(function(done)
      kv.get("secret/app/db", nil, done)
    end)
    assert.is_nil(err)
    assert.are.same({ USER = "u" }, secret.data)
    assert.are.equal(1, secret.version)
  end)

  it("reports not_found", function()
    local err = helpers.await(function(done)
      kv.get("secret/nope", nil, done)
    end)
    assert.are.equal("not_found", err.kind)
  end)

  it("lists one level and walks recursively", function()
    local _, entries = helpers.await(function(done)
      kv.list("secret/app", done)
    end)
    assert.are.same({ "api/", "db" }, entries)
    local _, all = helpers.await(function(done)
      kv.walk("secret", config.options.search, done)
    end)
    assert.are.same({ "secret/app/api/key", "secret/app/db" }, all)
  end)

  it("returns an empty list for an empty folder", function()
    local err, entries = helpers.await(function(done)
      kv.list("secret/empty", done)
    end)
    assert.is_nil(err)
    assert.are.same({}, entries)
  end)

  it("enforces check-and-set", function()
    local err = helpers.await(function(done)
      kv.put("secret/app/db", { USER = "x" }, { cas = 5 }, done)
    end)
    assert.are.equal("cas", err.kind)
    local ok_err, version = helpers.await(function(done)
      kv.put("secret/app/db", { USER = "x" }, { cas = 1 }, done)
    end)
    assert.is_nil(ok_err)
    assert.are.equal(2, version)
    assert.are.same({ USER = "x" }, helpers.latest(dir, "secret/app/db"))
  end)

  it("writes an empty secret as an empty object", function()
    helpers.await(function(done)
      kv.put("secret/blank", {}, { cas = 0 }, done)
    end)
    assert.are.same({}, helpers.latest(dir, "secret/blank"))
  end)

  it("lists versions, rolls back, deletes and undeletes", function()
    helpers.await(function(done)
      kv.put("secret/app/db", { USER = "v2" }, { cas = 1 }, done)
    end)
    local _, versions, current = helpers.await(function(done)
      kv.versions("secret/app/db", done)
    end)
    assert.are.equal(2, current)
    assert.are.equal(2, versions[1].version)
    helpers.await(function(done)
      kv.rollback("secret/app/db", 1, done)
    end)
    assert.are.same({ USER = "u" }, helpers.latest(dir, "secret/app/db"))
    helpers.await(function(done)
      kv.delete("secret/app/db", done)
    end)
    local err = helpers.await(function(done)
      kv.get("secret/app/db", nil, done)
    end)
    assert.are.equal("not_found", err.kind)
    helpers.await(function(done)
      kv.undelete("secret/app/db", { 3 }, done)
    end)
    local _, secret = helpers.await(function(done)
      kv.get("secret/app/db", nil, done)
    end)
    assert.are.same({ USER = "u" }, secret.data)
  end)

  it("fails clearly when no mount matches", function()
    config.options.mounts = { "other" }
    local err = helpers.await(function(done)
      kv.get("secret/app/db", nil, done)
    end)
    assert.matches("no KV v2 mount", err.msg)
  end)

  it("uses the longest matching mount", function()
    config.options.mounts = { "team", "team/kv" }
    local mounts = require("openbao.mounts")
    local mount, rel = helpers.await(function(done)
      mounts.resolve("team/kv/app/db", done)
    end)
    assert.are.equal("team/kv", mount)
    assert.are.equal("app/db", rel)
  end)
end)
