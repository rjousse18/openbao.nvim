local helpers = require("tests.helpers")
local auth = require("openbao.auth")
local client = require("openbao.client")
local kv = require("openbao.kv")

describe("auth", function()
  it("re-authenticates after an auth failure, then retries", function()
    local dir = helpers.setup_fake({ token_valid = false, secrets = { ["secret/a"] = { K = "v" } } })
    local restore = helpers.stub_select({ ["not authenticated"] = "Log in" })
    local err, secret = helpers.await(function(done)
      kv.get("secret/a", nil, done)
    end)
    restore()
    assert.is_nil(err)
    assert.are.same({ K = "v" }, secret.data)
    assert.are.equal(1, helpers.store(dir).logins)
  end)

  it("reports the original error when the user cancels the login", function()
    helpers.setup_fake({ token_valid = false })
    local restore = helpers.stub_select({ ["not authenticated"] = "Cancel" })
    local err = helpers.await(function(done)
      kv.get("secret/a", nil, done)
    end)
    restore()
    assert.are.equal("auth", err.kind)
  end)

  it("does not offer a login for a policy denial with a valid token", function()
    helpers.setup_fake()
    local restore, prompts = helpers.stub_select({})
    local err = helpers.await(function(done)
      kv.get("secret/forbidden/x", nil, done)
    end)
    restore()
    assert.are.equal("auth", err.kind)
    assert.are.same({}, prompts)
  end)

  it("does not prompt when login.auto is false", function()
    helpers.setup_fake({ token_valid = false })
    require("openbao.config").options.login.auto = false
    local restore, prompts = helpers.stub_select({})
    helpers.await(function(done)
      kv.get("secret/a", nil, done)
    end)
    restore()
    assert.are.same({}, prompts)
  end)

  it("shares one login between concurrent calls", function()
    local dir = helpers.setup_fake({ token_valid = false, secrets = { ["secret/a"] = { K = "v" } } })
    local restore = helpers.stub_select({ ["not authenticated"] = "Log in" })
    local results = {}
    helpers.await(function(done)
      for i = 1, 3 do
        kv.get("secret/a", nil, function(err)
          results[i] = err == nil
          if #results == 3 then
            done()
          end
        end)
      end
    end)
    restore()
    assert.are.same({ true, true, true }, results)
    assert.are.equal(1, helpers.store(dir).logins)
  end)

  it("reports a failed login", function()
    helpers.setup_fake({ token_valid = false, login_fails = true })
    local ok = helpers.await(function(done)
      auth.login(done)
    end)
    assert.is_false(ok)
  end)

  it("summarises the token", function()
    helpers.setup_fake()
    local lines = helpers.await(function(done)
      auth.status(done)
    end)
    assert.are.same({ "user: oidc-tester", "policies: default, dev", "ttl: 3600s" }, lines)
  end)

  it("classifies auth errors", function()
    assert.is_true(client.looks_like_auth_error({ stderr = "Code: 403. Errors: permission denied" }))
    assert.is_false(client.looks_like_auth_error({ stderr = "connection refused" }))
  end)
end)
